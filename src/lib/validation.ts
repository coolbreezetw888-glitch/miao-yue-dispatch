/** 台灣手機號碼格式:09 開頭、共 10 碼純數字,不允許空格/破折號/加號等其他字元。 */
export const TW_MOBILE_PHONE_REGEX = /^09\d{8}$/;

/** 檢查是否為合法的台灣手機號碼格式(09 開頭、共 10 碼數字)。 */
export function isValidTaiwanMobilePhone(phone: string): boolean {
  return TW_MOBILE_PHONE_REGEX.test(phone);
}

/** 白話錯誤訊息,§8.1/§8.2 表單驗證失敗時共用同一句文案。 */
export const TW_MOBILE_PHONE_ERROR_MESSAGE = "請輸入正確的手機號碼格式，例如 0912345678";

// ---------------------------------------------------------------------------
// Email 格式驗證。
//
// ─── 為什麼需要(2026-09-24 稽核抓到)─────────────────────────────────────────
// 建單表單的「客戶 Email」欄位雖然寫了 <input type="email">,但那個原生格式驗證**從來不會
// 觸發**——因為那顆送出按鈕是 type="button" + onClick,外面也沒有包 <form>,瀏覽器根本沒有
// 「提交表單」這個動作可以觸發驗證。結果客服隨手打 `abc`(或誤把地址貼進去)就直接存進資料庫。
//
// 服務人員/客服的電話早就有 isValidTaiwanMobilePhone 嚴格把關(StaffListPage、AgentListPage、
// EditMyStaffProfileDialog 三處),客戶 Email 這邊卻一條驗證都沒有,所以補上這支共用函式,
// 一樣放在這個檔案讓各表單 import,不要各自在元件內寫一份正規表示式。
//
// ─── 刻意寫得寬鬆 ───────────────────────────────────────────────────────────
// 這裡的目的是擋掉「明顯不是 Email」的輸入(沒有 @、沒有網域、含空白),不是要完整實作
// RFC 5322——過嚴的正規表示式反而會誤擋掉合法但少見的位址(例如 name+tag@example.co.uk),
// 對客服來說「明明是對的卻存不進去」比「偶爾放過一個怪字串」更困擾。
// 真正確認 Email 有效的唯一方法是實際寄一封信出去,那不在這個欄位的職責範圍內。
// ---------------------------------------------------------------------------

/** Email 格式:@ 前後都要有內容、網域至少要有一個點、整串不能有空白字元。 */
export const EMAIL_REGEX = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

/** 檢查是否為合法的 Email 格式。注意:**空字串會回 false**,「選填欄位留空要放行」這件事
 * 由呼叫端自己先判斷(例如 `if (email.trim() && !isValidEmail(email)) { ... }`),
 * 這支函式本身不決定某個欄位是必填還是選填。 */
export function isValidEmail(email: string): boolean {
  return EMAIL_REGEX.test(email.trim());
}

/** 白話錯誤訊息,各表單 Email 驗證失敗時共用同一句文案。 */
export const EMAIL_ERROR_MESSAGE = "請輸入正確的 Email 格式，例如 name@example.com";

// ---------------------------------------------------------------------------
// 「客戶電話」格式驗證(手機或市話皆可)。SPECS-INDEX #822。
//
// ─── 為什麼另外開一支,而不是沿用上面的 isValidTaiwanMobilePhone ─────────────────
// 服務人員/客服的電話規則是「只收手機」(那是刻意的,merchant_staff.phone 甚至有資料庫 CHECK),
// 但客戶可能留市話。2026-09-24 稽核時因此**刻意不對客戶電話做手機驗證**——結果做過頭了,變成
// 任何非空字串都放行,正式庫實查已有 3 碼、40 碼的髒資料。這支函式是 2026-09-27 使用者裁決後
// 補上的「客戶電話」專用規則,**不要拿它去改服務人員/客服那邊**,兩邊的嚴格程度本來就不同。
//
// ─── 規則(使用者 2026-09-27 裁決,原話整理)────────────────────────────────────
//   ・手機:0 + 9 + 8 碼,共 10 碼(例如 0912345678)
//   ・市話:0 + 第二碼 2~8 + 7~8 碼,共 9~10 碼(例如 02-1234-5678 台北 10 碼、037-123456 苗栗 9 碼、
//     0823-12345 金門 9 碼)
//   ・市話分機:市話後面接「#」+ 數字(例如 02-1234-5678#123)
//   ・分隔符號(- 空白 括號)**不強制**,只是方便看數字;判斷前先去掉。**但 # 要保留**,它是分機
//     的分隔符,不是排版用的。
//
// 🔴 不要改成列舉區碼。主腦已用使用者給的 13 個區碼(02/03/037/04/049/05/06/07/08/089/0823/0826/0836)
//    逐一驗算,全部符合「0 開頭、第二碼非 9、去掉分隔符號後共 9~10 碼」;列舉會漏,日後區碼異動
//    還要改程式。
//
// ─── 這條規則目前只做「前端」+「後端函式」兩層,沒有資料庫 CHECK 約束 ─────────────────
// 不是漏做,是做不到:正式庫已有髒資料(3 碼 3 筆、40 碼 23 筆),alter table add constraint 會直接
// 失敗。等 SPECS-INDEX #638 把舊資料清乾淨之後才補得上去。舊髒資料依使用者裁決先不動。
// 後端那一層在 supabase/migrations/20260927010000_normalize_phone_extension.sql 的
// private.is_valid_taiwan_phone(),正規表示式跟這裡**逐字對應**,改這裡時務必同步改那邊。
// ---------------------------------------------------------------------------

/** 判斷前要先去掉的排版用分隔符號:空白(含全形)、連字號、括號。注意 **不包含 #**。 */
export const TW_PHONE_SEPARATOR_REGEX = /[\s()-]/g;

/** 去掉分隔符號之後的完整格式:手機 10 碼,或市話 9~10 碼(可接 #1~6 碼分機)。 */
export const TW_PHONE_COMPACT_REGEX = /^(?:09\d{8}|0[2-8]\d{7,8}(?:#\d{1,6})?)$/;

/** 檢查是否為合法的台灣電話(手機或市話皆可,市話可帶 # 分機,分隔符號會先被忽略)。
 * 注意:**空字串會回 false**,「選填欄位留空要放行」由呼叫端自己先判斷(跟 isValidEmail 同一個慣例)。 */
export function isValidTaiwanPhone(phone: string): boolean {
  return TW_PHONE_COMPACT_REGEX.test(phone.replace(TW_PHONE_SEPARATOR_REGEX, ""));
}

/** 白話錯誤訊息,建單/會員各表單的客戶電話驗證失敗時共用同一句文案。 */
export const TW_PHONE_ERROR_MESSAGE =
  "電話格式不正確。手機請填 09 開頭共 10 碼(例如 0912345678)；市話請連同區碼一起填、共 9~10 碼(例如 02-1234-5678 或 037-123456)，有分機的話用 # 接在後面(例如 02-1234-5678#123)";
