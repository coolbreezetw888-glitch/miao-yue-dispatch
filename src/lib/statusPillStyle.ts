/**
 * 訂單狀態膠囊(實心填入商家自訂色)的完整 inline style —— 底色原值 + **一律白字** + 深色描邊。
 *
 * ## 🔴 為什麼是「一律白字」(2026-09-30 使用者裁決,SPECS-INDEX #832)
 *
 * 使用者原話:**「一律白字,顏色完全不動」**。
 *
 * 這是在**已經被明確告知可讀性代價之後**做的裁決,不是漏想到:
 *   ・「涼風工匠」實際設定的 4 個顏色,白字的 WCAG 對比度分別是
 *     待確認 `#662deb`(深紫)8.6:1 ✅ / 已接受 `#ff42dc`(亮桃紅)2.9:1 /
 *     已完成 `#07cf68`(亮綠)1.9:1 / 已取消 `#ffaa33`(橘)2.0:1。
 *   ・12px 小字的 WCAG AA 門檻是 4.5:1 ⇒ 亮綠與橘上的白字只有標準值的 **40%~45%**,
 *     亮桃紅約 65%。也就是說**這三顆膠囊的文字在強光下會很難讀**。
 *   ・使用者聽完仍然選這個,理由是「顏色完全不動」比「字一定讀得清楚」重要
 *     (他要的是一眼用顏色分辨狀態,文字只是輔助)。
 *
 * 🔴 **所以不要因為「對比度不足」就把這支改回「依底色亮度自動挑黑或白」。**
 * 上一版(2026-09-30 當天早一批)做的就是自動挑色(檔名 `src/lib/readableTextColor.ts`,
 * 含 WCAG gamma 解碼 / 相對亮度 / 對比度比較),**被使用者當面推翻**,整支連測試一起移除。
 * 要改回去必須是**使用者自己**再改一次裁決,不是工程師或品管看到對比度數字就動手。
 * (檔名也因此從 `readableTextColor.ts` 改成現在這個 —— 一個叫「可讀文字色」的檔案裡面
 *  寫死白字,等於在邀請下一個人把它「修正」回來。)
 *
 * ## 🔴 邊框為什麼是「深色」半透明,而不是文字色的半透明
 *
 * 舊版邊框是「文字色的 25% 透明度」。文字色固定白色之後,那個寫法會變成
 * **白底卡片 + 白邊 + 白字** —— 商家只要挑一個很淺的顏色(`#fffdf5` 這種),
 * 整顆膠囊會在卡片上完全消失,連「這裡有一顆膠囊」都看不出來。
 *
 * 改成固定的深色(專案的墨色 `#111827`)25% 透明度,兩個極端都成立:
 *   ・**很淺的底色** → 深色描邊在白卡片上清楚可見,膠囊輪廓在。
 *   ・**很深的底色** → 描邊本身融進底色,但底色自己跟白卡片對比很強,輪廓一樣看得到。
 *
 * 這條**不是使用者裁決的一部分**,是防止整顆膠囊看不見的保命線,不需要問使用者。
 *
 * ## 使用點(改這支會同時動到這兩處,它們必須永遠一致)
 *
 *   1. `components/patterns/Tags.tsx` 的 `StatusTag fillColor=`
 *      → 訂單管理 / 行事曆的訂單狀態膠囊(`modules/booking/OrdersPage.tsx`)。
 *   2. `modules/merchant/MerchantSettingsPage.tsx` 訂單狀態顏色設定卡的**即時預覽色塊**。
 *
 * 🔴 **預覽跟實際一定要走同一支純函式。** 2026-09-30 踩過一次:預覽寫死白字、實際是自動挑的
 * 黑字,商家在設定頁看到的跟訂單頁看到的不一樣。**不要為了省事在任何一邊寫死顏色**,
 * 也不要反過來變成「預覽黑字、實際白字」。
 *
 * ⚠️ 純函式、沒有 React 依賴,所以放在 `src/lib` 而不是 `components/patterns` ——
 *    元件層(Tags.tsx)跟功能模組(merchant 設定頁)都要用它,元件層不該去 import 功能模組。
 */

/** 膠囊文字色。🔴 一律白字(見檔頭的使用者裁決),不依底色計算。 */
export const STATUS_PILL_INK = "#ffffff";

/**
 * 膠囊描邊色:專案墨色 `#111827` 的 25% 透明度。
 * 🔴 固定深色,**不可以**改成跟著文字色走(那會在淺底色上變成白邊 + 白字 = 整顆消失)。
 */
export const STATUS_PILL_BORDER = "rgba(17, 24, 39, 0.25)";

export interface StatusPillStyle {
  backgroundColor: string;
  color: string;
  borderColor: string;
}

/**
 * 實心膠囊 / 實心色塊的完整 inline style。
 *
 * `background` 是商家自訂的色碼字串,**原樣輸出、不做任何加深或調整**
 * (使用者裁決的「顏色完全不動」就是這一句)。所以這支函式刻意**不解析顏色** ——
 * 沒有任何一條分支需要知道底色是深還是淺,也就不需要 hex / rgb() 解析器。
 * 解析不出來的字串(CSS 顏色名稱、`hsl()`)一樣原樣交給瀏覽器處理,不噴錯、不阻擋操作。
 */
export function solidFillStyle(background: string): StatusPillStyle {
  return {
    backgroundColor: background,
    color: STATUS_PILL_INK,
    borderColor: STATUS_PILL_BORDER,
  };
}
