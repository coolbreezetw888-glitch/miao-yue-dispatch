-- SPECS-INDEX #850:內部備註可以「逐單」對服務人員隱藏 —— 第 1 步,只加欄位。
-- 規格書:.project/specs/內部備註對服務人員隱藏.md(#850)
--
-- ─── 為什麼叫 hide_notes_from_staff(正面命名,true = 隱藏)─────────────────────
-- 客服在畫面上勾的是「**不**讓服務人員看到」,勾起來 = true。用 hide_... 可以讓
-- 「畫面上的勾選狀態」跟「資料庫裡的值」方向完全一樣,不需要在任何一層做反轉。
-- 反轉方向是這類布林最常見的 bug,而這裡寫錯方向的後果是「該藏的洩漏出去」,代價太高。
-- (主腦 2026-09-30 裁決 T2。)
--
-- ─── 為什麼 default false ────────────────────────────────────────────────────
-- 使用者要的是「**預設**服務人員看得到」。false = 不隱藏 = 看得到,所以這條 migration 跑完
-- 的那一瞬間,既有的每一筆訂單都還是「服務人員看得到」,沒有任何一筆訂單的可見性被這次改動
-- 悄悄改掉。
--
-- ─── 為什麼 not null ────────────────────────────────────────────────────────
-- 布林可空會變三態(true / false / null),每個讀取的地方都要記得處理 null,遲早有人漏掉;
-- 漏掉時如果被當成「不確定就藏」就是功能壞掉。直接用 not null default false 消滅三態。
--
-- ─── 效能 ───────────────────────────────────────────────────────────────────
-- PostgreSQL 11 以後,加「有預設值的 not null 欄位」不會重寫整張表,是瞬間完成的 metadata
-- 變更,既有訂單多寡都不影響。
--
-- 這一步刻意單獨一支 migration:它完全不改變任何既有行為,可以先確認跑得過,再往下做遮蔽。

alter table public.bookings
  add column hide_notes_from_staff boolean not null default false;

comment on column public.bookings.hide_notes_from_staff is 'SPECS-INDEX #850(2026-09-30 使用者需求):這一筆訂單的「內部備註」(bookings.notes)要不要對服務人員隱藏。true = 隱藏(服務人員端完全看不到備註區塊,跟這筆訂單沒有備註一樣,不顯示任何「有東西被藏起來」的提示 —— 主腦裁決 T1=A);false(預設)= 服務人員看得到,跟 2026-09-30 之前的行為完全一致。逐單設定,不是商家層級的全店開關。遮蔽實作在 public.get_my_booking_schedule(服務人員端唯一的訂單來源,SECURITY DEFINER),不是只在前端不 render —— 服務人員端是手機瀏覽器直打 Supabase,只要 API 回應裡帶著那段文字,開發者工具的 Network 面板就看得到。商家管理員/客服(private.can_manage_bookings)不受這個旗標影響,永遠看得到自己寫的備註,否則無法取消勾選。';
