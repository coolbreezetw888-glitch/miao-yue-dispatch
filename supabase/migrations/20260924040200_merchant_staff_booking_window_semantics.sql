-- 2026-09-24:預約天數欄位從「三個」收斂成「兩個」,並修掉會直接擋下使用者舉例數字的約束。
--
-- =========================================================================
-- 【背景:前端已經改完,資料庫這邊必須配合,否則畫面存不下去】
-- 前端(另一位工程師)這批把服務人員的預約天數設定從三個欄位收斂成兩個:
--   ・「最少要提前幾天預約」 → 沿用既有欄位 advance_booking_days(⚠️ 語意反轉,見下)
--   ・「最遠可以預約到幾天後」→ 沿用既有欄位 booking_window_max_days
--   ・booking_window_min_days → 從畫面整個廢除
-- 刻意不改欄位名(改名會牽動 src/integrations/supabase/types.ts 重新產生,成本遠大於收益)。
--
-- =========================================================================
-- 【⚠️ 為什麼非改不可:使用者自己舉的例子會被現有約束當場擋下】
-- 20260916100000_staff_agent_schema.sql:29-30 當初把兩個天數欄位都加上了
--   check (... is null or (... between 3 and 180))
-- 這是「只存值、不連動任何邏輯」那個階段隨手訂的範圍(規格書 1.1.1)。
-- 但「最遠可以預約到幾天後」這個新語意下,使用者自己舉的例子是 **365**(一年後),
-- 365 > 180 → 會被 CHECK 直接擋下,商家在畫面上存檔會拿到一個資料庫原始錯誤。
-- 這不是理論風險,是使用者明確講出來的使用情境。
--
-- =========================================================================
-- 【資料遷移風險:零。已自行對正式環境唯讀查證,不是採信轉述】
-- select count(*), count(booking_window_min_days), count(booking_window_max_days),
--        count(advance_booking_days) from public.merchant_staff;
--   → total_rows=125、min_days_not_null=0、max_days_not_null=0、advance_days_not_null=0
-- 也就是 125 列 merchant_staff 這三個欄位 **100% 都是 null**(這批設定一直沒有人真的填過)。
-- 所以:
--   ・advance_booking_days 的語意反轉不需要任何資料轉換(沒有任何舊值需要重新解讀)。
--   ・drop booking_window_min_days 不會遺失任何資料,符合
--     .claude/skills/supabase-permission-hygiene 的「drop 欄位前要回填」規則
--     (這裡沒有任何東西需要回填)。
--   ・放寬 booking_window_max_days 的上限不會讓任何既有資料變成不合法。
-- =========================================================================

-- =========================================================================
-- §1 drop booking_window_min_days(下限欄位已從畫面廢除)。
--
-- ⚠️ 這個 drop 會「連帶」自動刪掉兩條約束,所以下面不需要(也不能)再單獨 drop 它們:
--   (1) 這個欄位自己的 CHECK(自動命名 merchant_staff_booking_window_min_days_check)
--   (2) 表層級的 merchant_staff_booking_window_range(min <= max 的跨欄位約束)——
--       它的定義引用了 booking_window_min_days,欄位被 drop 時 Postgres 會一併移除。
-- 為了讓意圖明確(而不是依賴這個連帶行為讓之後的人自己推理),下面 §2 仍然寫一行
-- `drop constraint if exists`,加了 if exists 所以重複執行也不會失敗。
-- =========================================================================
alter table public.merchant_staff
  drop column if exists booking_window_min_days;

-- =========================================================================
-- §2 明確移除 min <= max 這條跨欄位約束(上面 drop column 已經連帶移除,這行是意圖宣告)。
-- 下限欄位既然廢除了,「下限不能大於上限」這條規則就沒有意義,留著只會在之後有人重新
-- 引入某個下限概念時莫名其妙咬人。
-- =========================================================================
alter table public.merchant_staff
  drop constraint if exists merchant_staff_booking_window_range;

-- =========================================================================
-- §3 放寬 booking_window_max_days 的範圍:between 3 and 180 → between 0 and 3650。
--
-- ・下限從 3 改成 **0**(2026-09-24 使用者追加裁決)。使用者原話:
--     「應該是最遠可預約到幾天後設置為 0 才是代表一定要當天預約當天完成
--       (但這種情況應該幾乎為 0 不過就預留這個可能性)。」
--   0 的語意 = 最遠只能約到今天 → 只接受「當天預約、當天服務」。使用者明講這種設定幾乎不會
--   用到,但要求預留這個可能性,所以下限開到 0 而不是 1。
--   (中間曾經放寬成 between 1 and 3650,理由是「只能預約明天」合理;使用者進一步指出 0 才是
--    真正的邊界情況,已照裁決改成 0。)
-- ・上限從 180 改成 3650(約十年):直接容納使用者舉的 365,並留下充裕餘裕。
--   刻意「不」整條移除約束——保留一個上限可以擋掉打錯字的離譜數字(例如把 30 打成
--   3000000),那種值會讓之後的預約可選日期計算跑出無意義的巨大範圍。
--
-- 約束名稱是 create table 裡 inline CHECK 自動產生的,慣例是
-- <表名>_<欄位名>_check → merchant_staff_booking_window_max_days_check。
-- 用 if exists 保險(萬一某個環境的自動命名不同,drop 不會失敗,新約束照樣加上去)。
-- =========================================================================
alter table public.merchant_staff
  drop constraint if exists merchant_staff_booking_window_max_days_check;

alter table public.merchant_staff
  add constraint merchant_staff_booking_window_max_days_check
  check (booking_window_max_days is null or (booking_window_max_days between 0 and 3650));

-- =========================================================================
-- §4 advance_booking_days 加上「不可為負數」的防呆約束。
--
-- ⚠️ 這一條不在前端工程師列的四件事裡,是我主動加的,理由與風險都寫清楚讓主腦判斷:
--   ・新語意「最少要提前幾天預約」,0 是合理值(當天就可以預約),負數沒有任何意義。
--   ・這個欄位原本完全沒有約束,也就是目前打 -5 會被靜默存進資料庫,之後真的實作預約
--     邏輯的人會拿到一個不可能的值。與其靜默存壞資料,不如當場擋下。
--   ・既有資料 125 列全部是 null,加約束不會失敗。
--   ・代價:商家如果真的在畫面上輸入負數,會看到資料庫原始錯誤而不是白話訊息。
--     已在回報中提醒前端補一個表單層驗證(`min={0}`)。
-- =========================================================================
alter table public.merchant_staff
  add constraint merchant_staff_advance_booking_days_check
  check (advance_booking_days is null or advance_booking_days >= 0);

-- =========================================================================
-- §5 改寫欄位註解(必做,而且是這支 migration 裡最容易被忽略卻最會害人的一項)。
--
-- advance_booking_days 這個欄位原本的語意是「**最多**可以提前幾天預約」,新語意是
-- 「**最少**要提前幾天預約」——方向完全相反,欄位名卻沿用不變。
-- 如果不改註解,之後真正實作預約可選日期計算的人照舊註解寫,會把規則寫成反的
-- (本來要擋「太趕的預約」,結果變成擋「太早的預約」),而且這種錯誤在畫面上很難一眼看出來。
-- =========================================================================
